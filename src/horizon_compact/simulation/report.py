FAMILY_TARGET = 0.05 / 16
REACHABLE_EXPECTED = 0.54
POWER_TARGET = 0.80


def wilson(k: int, n: int, z: float = 1.959963984540054) -> tuple[float, float]:
    if n == 0:
        return 0.0, 1.0
    p = k / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z / (1 + z * z / n) * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return max(0.0, centre - half), min(1.0, centre + half)


def pct(x: float | None, digits: int = 2) -> str:
    return "n/a" if x is None else f"{100 * x:.{digits}f}%"


def _cell(value: Any) -> str:
    """A table cell: a pipe would end the cell, even inside backticks, so it is escaped."""
    return str(value).replace("|", "\\|")


def table(header: Sequence[str], rows: Iterable[Sequence[Any]]) -> list[str]:
    out = [
        "| " + " | ".join(_cell(h) for h in header) + " |",
        "|" + "|".join("---" for _ in header) + "|",
    ]
    out += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return out


def points(x: float) -> str:
    """A share difference in points (0.081 is 8.1 points)."""
    return f"{100 * x:.1f} points"


def parse_key(key: str) -> dict[str, str]:
    return dict(part.split("=", 1) for part in key.split("|") if "=" in part)


def rate(point: dict[str, Any], verdict: str) -> float:
    return float(point["verdicts"][verdict]) / float(point["reps"])


def alone(point: dict[str, Any], verdict: str) -> float:
    """The rate of ``verdict`` from the Welch interval alone, before decision 10's two rules."""
    return float(point["interval_alone"][verdict]) / float(point["reps"])


def _judge(k: int, n: int, target: float) -> str:
    low, _ = wilson(k, n)
    if k / n <= target:
        return "met"
    return "clearly missed" if low > target else "missed"


# --- the summary --------------------------------------------------------------------------------------------


def _header(doc: dict[str, Any], title: str) -> list[str]:
    return [
        f"# {title}",
        "",
        f"> Generated by `hc simulate report` from `{RESULTS_NAME}`. Do not edit by hand: re-run the report.",
        f"> Mode `{doc['mode']}`; code and data hash `{doc['code_sha256'][:16]}` ({doc['code_files']} files);",
        f"> Python {doc['python']}, numpy {doc['libraries']['numpy']}, scipy {doc['libraries']['scipy']},",
        f"> statsmodels {doc['libraries']['statsmodels']}; alpha {doc['constants']['alpha']}; shares by the "
        f"{doc['constants']['share_interval']} interval, floor {doc['constants']['share_floor']:.4f}.",
        "",
    ]


def _points_at(grid: dict[str, Any], d: str) -> list[tuple[str, dict[str, Any]]]:
    """The grid points at true difference ``d`` that exist."""
    return [
        (key, point)
        for key, point in grid.items()
        if "skipped" not in point and parse_key(key)["d"] == d
    ]


def _worst_by(
    rows: list[tuple[str, dict[str, Any]]], verdict: str, by: tuple[str, str]
) -> dict[tuple[str, str], tuple[float, str]]:
    worst: dict[tuple[str, str], tuple[float, str]] = {}
    for key, point in rows:
        p = parse_key(key)
        cell = (p[by[0]], p[by[1]])
        r = rate(point, verdict)
        if cell not in worst or r > worst[cell][0]:
            worst[cell] = (r, key)
    return worst


def _grid_table(rows: list[tuple[str, dict[str, Any]]], verdict: str, pi: str) -> list[str]:
    mine = [(k, p) for k, p in rows if parse_key(k)["pi"] == pi]
    worst = _worst_by(mine, verdict, ("sigma", "n"))
    sigmas = sorted({c[0] for c in worst}, key=float)
    ns = sorted({c[1] for c in worst}, key=int)
    return table(
        ["sigma \\ n per wording", *ns],
        [[s, *(pct(worst[(s, n)][0]) if (s, n) in worst else "-" for n in ns)] for s in sigmas],
    )


