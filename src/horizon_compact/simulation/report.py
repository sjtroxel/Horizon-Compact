# --- the matcher --------------------------------------------------------------------------------------------


def matcher_calibration(doc: dict[str, Any]) -> str:
    lines = _header(doc, "Phase 3: the matcher's calibration")
    m = doc["matcher"]
    lines += [
        "`D*` and `k*` for each scenario shape (Phase 3 IMPLEMENTATION doc sections 13.3, 13.4 and 14.2),",
        "set from synthetic cases with a known answer before any real case runs. Each trial builds one case",
        "with `simulation/matcher_cases.build_case`, seeded by `matcher_sim.trial_seed(shape, kind, sigma, k,",
        "trial)`, so any single trial can be rebuilt; the matcher is the analysis's own `match_case`, with",
        f"{doc['constants']['match_resamples']:,} resamples for its 95% intervals. Ten repeats per wording,",
        "five objectives, three wordings.",
        "",
        "- `D*`: the 95th percentile of the true-match cases' nearest distance at the widest spread.",
        "- `k*`: the smallest number of observable dimensions at which the generating objective is nearest",
        "  or tied with the nearest in at least 80% of sparse trials at the design spread. Dimensions are",
        "  counted as the matcher counts them: the choice one, `n` observable lines `n - 1` (step 12). A",
        "  sparse trial observes `k` raw items and is grouped by the dimensions its decision has.",
        "- **Opposite check** (step 12, his decision 2, as recommended): the generating objective's own",
        "  distance to its opposite case must exceed `D*` in at least 95% of trials, which is what the check",
        "  is for: the matcher separates an objective from its opposite. The nearest distance is reported",
        "  beside it: with five random profiles another objective usually sits near the opposite decision, so",
        '  "no good match" stays rare, and the methods page must say so.',
        "- **Unmatchable:** the matcher refused the case (an objective had no distanceable run in a wording;",
        "  matcher finding (b)). Counted, never identified.",
        "",
        *table(
            [
                "Shape",
                "D*",
                "k*",
                "Opposite: its own objective above D*, by spread",
                "Opposite: nearest above D* (reported)",
                "Opposite check",
            ],
            [
                [
                    shape,
                    f"{s['d_star']:.4f}",
                    "none reaches 80%" if s["k_star"] is None else s["k_star"],
                    ", ".join(
                        f"{c['sigma']:g}: {pct(c['generating_above_d_star'] / c['trials'], 1)}"
                        for key, c in s["cells"].items()
                        if c["kind"] == "opposite"
                    ),
                    ", ".join(
                        f"{c['sigma']:g}: {pct(c['nearest_above_d_star'] / c['trials'], 1)}"
                        for key, c in s["cells"].items()
                        if c["kind"] == "opposite"
                    ),
                    "met"
                    if all(
                        c["generating_above_d_star"] / c["trials"] >= 0.95
                        for c in s["cells"].values()
                        if c["kind"] == "opposite"
                    )
                    else "**missed**",
                ]
                for shape, s in m.items()
            ],
        ),
        "",
        "## Identification by observable dimensions (sparse cases, design spread)",
        "",
    ]
    for shape, s in m.items():
        lines += [
            f"{shape} (design spread {s['design_spread']:g}): "
            + ", ".join(
                f"{k} dimension(s): {pct(v, 1)}"
                for k, v in s["identification_by_dimensions_at_design_spread"].items()
            ),
            "",
        ]
    lines += ["## Labels with D* and k* applied, by case type and spread", ""]
    for shape, s in m.items():
        rows = []
        for key, c in s["cells"].items():
            labels = c["labels"]
            n = c["trials"]
            near = c["nearest"]
            rows.append(
                [
                    f"`{key}`",
                    pct(c["identified"] / n, 1),
                    *(
                        pct(labels[name] / n, 1)
                        for name in (
                            "match",
                            "tie",
                            "no_good_match",
                            "not_enough_disclosed",
                            "unmatchable",
                        )
                    ),
                    "n/a" if near is None else f"{near['median']:.3f} / {near['p95']:.3f}",
                ]
            )
        lines += [
            f"### {shape}: D* = {s['d_star']:.4f}, k* = {s['k_star']}",
            "",
            *table(
                [
                    "Cell (key)",
                    "Identified",
                    "Match",
                    "Tie",
                    "No good match",
                    "Not enough",
                    "Unmatchable",
                    "Nearest distance median / p95",
                ],
                rows,
            ),
            "",
        ]
    return "\n".join(lines).rstrip() + "\n"


def write_reports(folder: Path) -> list[Path]:
    doc = json.loads((folder / RESULTS_NAME).read_text(encoding="utf-8"))
    written = []
    for name, text in ((SUMMARY_NAME, summary(doc)), (MATCHER_NAME, matcher_calibration(doc))):
        path = folder / name
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(path)
    return written


def thresholds_toml(doc: dict[str, Any]) -> str:
    """The text of ``analysis/matcher_thresholds.toml`` from the results: each shape's ``D*`` and ``k*``. A
    shape where no dimension count reached 80% gets one more than the most it was measured at, so the
    matcher calls every case of it "not enough disclosed" rather than matching on evidence that cannot
    separate the objectives."""
    lines = [
        "# The matcher's thresholds per scenario shape (Phase 3 IMPLEMENTATION doc sections 13.3 and 14.2).",
        "# Written from docs/phases/evidence/phase-3/simulation-results.json by",
        "# horizon_compact.simulation.report.thresholds_toml; a test holds the two equal. Data, not code, so",
        "# that writing it leaves the hash the results record unchanged. Frozen with analysis/ at the tag.",
        f"# Results code hash: {doc['code_sha256']}",
        "",
    ]
    for shape, s in doc["matcher"].items():
        k = s["k_star"]
        note = ""
        if k is None:
            k = max(int(x) for x in s["identification_by_dimensions_at_design_spread"]) + 1
            note = "  # no dimension count reached 80%: never matched"
        lines += [f"[shapes.{shape}]", f"d_star = {s['d_star']!r}", f"k_star = {k}{note}", ""]
    return "\n".join(lines).rstrip() + "\n"
